#!/usr/bin/env node
/**
 * Central OpenClaw runtime config initializer.
 *
 * Generates the active OpenClaw config and runtime auth profiles from a single
 * free-first / paid-last model policy. Secrets are written only to OpenClaw's
 * runtime auth store and local .env; never into openclaw.json.
 *
 * Usage: node scripts/init-openclaw-config.js [env-path] [config-path]
 */

const fs = require('fs');
const path = require('path');

const repoRoot = path.resolve(__dirname, '..');
const home = process.env.HOME || process.env.USERPROFILE || process.cwd();
const openclawHome = process.env.OPENCLAW_HOME || path.join(home, '.openclaw');
const envPath = process.argv[2] || process.env.OPENCLAW_ENV_PATH || path.join(openclawHome, '.env');
const configPath = process.argv[3] || process.env.OPENCLAW_CONFIG_PATH || path.join(openclawHome, 'openclaw.json');
const policyPath = process.env.CLAW_MODEL_POLICY_PATH || path.join(repoRoot, 'config', 'model-policy.json');
const stateRoot = path.dirname(configPath);

function parseEnvFile(filePath) {
  if (!fs.existsSync(filePath)) return {};
  const env = {};
  const content = fs.readFileSync(filePath, 'utf8');
  for (const line of content.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eqIdx = trimmed.indexOf('=');
    if (eqIdx === -1) continue;
    const key = trimmed.slice(0, eqIdx).trim();
    let value = trimmed.slice(eqIdx + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) ||
        (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    env[key] = value;
  }
  return env;
}

function truthy(value) {
  return ['1', 'true', 'yes', 'on'].includes(String(value || '').trim().toLowerCase());
}

function mergeEnv(fileEnv) {
  const merged = { ...fileEnv };
  for (const [key, value] of Object.entries(process.env)) {
    if (value !== undefined && value !== '') merged[key] = value;
  }
  return merged;
}

function uniqueBy(items, keyFn) {
  const seen = new Set();
  const result = [];
  for (const item of items) {
    const key = keyFn(item);
    if (seen.has(key)) continue;
    seen.add(key);
    result.push(item);
  }
  return result;
}

function setDeep(obj, keyPath, value) {
  const keys = keyPath.split('.');
  let current = obj;
  for (let i = 0; i < keys.length - 1; i++) {
    if (!current[keys[i]] || typeof current[keys[i]] !== 'object') current[keys[i]] = {};
    current = current[keys[i]];
  }
  current[keys[keys.length - 1]] = value;
}

function deleteDeep(obj, keyPath) {
  const keys = keyPath.split('.');
  let current = obj;
  for (let i = 0; i < keys.length - 1; i++) {
    if (!current?.[keys[i]]) return;
    current = current[keys[i]];
  }
  delete current[keys[keys.length - 1]];
}

function collectKnownEnvKeys(policy) {
  const keys = new Set([
    policy.paidFallbackEnv,
    'CLAW_BRANCH',
    'CLAW_ENABLE_PAID_FALLBACK',
    'CLAW_AGENT_MESSAGE',
    'CLAW_AGENT_TIMEOUT',
    'CLAW_SYNC_PATHS',
    'CLAW_PROBE_MODELS',
    'TELEGRAM_BOT_TOKEN',
    'DISCORD_BOT_TOKEN',
  ]);
  for (const provider of Object.values(policy.providers)) {
    for (const profile of [...(provider.freeProfiles || []), ...(provider.paidProfiles || [])]) {
      keys.add(profile.env);
    }
  }
  return [...keys].filter(Boolean).sort();
}

function writeEnvFile(filePath, env, keys) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  const lines = [
    '# OpenClaw runtime secrets',
    '# Generated by scripts/init-openclaw-config.js. Do not commit this file.',
    '',
  ];
  for (const key of keys) {
    if (env[key]) lines.push(`${key}=${env[key]}`);
  }
  fs.writeFileSync(filePath, `${lines.join('\n')}\n`);
}

function collectProviderProfiles(providerId, providerPolicy, env, paidEnabled) {
  const candidates = [];
  for (const profile of providerPolicy.freeProfiles || []) {
    if (env[profile.env]) candidates.push({ ...profile, provider: providerId, authProvider: providerPolicy.authProvider || providerId, tier: 'free', key: env[profile.env] });
  }
  if (paidEnabled) {
    for (const profile of providerPolicy.paidProfiles || []) {
      if (env[profile.env]) candidates.push({ ...profile, provider: providerId, authProvider: providerPolicy.authProvider || providerId, tier: 'paid', key: env[profile.env] });
    }
  }
  return uniqueBy(candidates, (profile) => `${profile.authProvider}:${profile.key}`);
}

function providerFromModelRef(ref) {
  return String(ref).split('/')[0];
}

function buildModelChain(policy, profilesByProvider, paidEnabled) {
  const freeModels = [];
  const paidModels = [];
  for (const [providerId, providerPolicy] of Object.entries(policy.providers)) {
    if (!providerPolicy.enabled || !profilesByProvider[providerId]?.length) continue;
    for (const model of providerPolicy.models?.free || []) freeModels.push({ ...model, tier: 'free' });
    if (paidEnabled && profilesByProvider[providerId].some((profile) => profile.tier === 'paid')) {
      for (const model of providerPolicy.models?.paid || []) paidModels.push({ ...model, tier: 'paid' });
    }
  }

  const overrideFree = splitCsv(process.env.CLAW_FREE_MODEL_CHAIN);
  const overridePaid = paidEnabled ? splitCsv(process.env.CLAW_PAID_MODEL_CHAIN) : [];
  const fromOverrides = [...overrideFree.map((ref) => ({ ref, tier: 'free', alias: ref })), ...overridePaid.map((ref) => ({ ref, tier: 'paid', alias: ref }))]
    .filter((model) => profilesByProvider[providerFromModelRef(model.ref)]?.length);

  return uniqueBy(fromOverrides.length ? fromOverrides : [...freeModels, ...paidModels], (model) => model.ref);
}

function splitCsv(value) {
  return String(value || '')
    .split(',')
    .map((part) => part.trim())
    .filter(Boolean);
}

function buildConfig(baseConfig, policy, env, profilesByProvider, modelChain, paidEnabled) {
  const config = baseConfig && typeof baseConfig === 'object' ? baseConfig : {};
  delete config.env;
  delete config.name;
  delete config.model;
  delete config.api_key;
  delete config.workspace_path;
  deleteDeep(config, 'server');
  deleteDeep(config, 'costPolicy');
  deleteDeep(config, 'channels.telegram.botToken');
  deleteDeep(config, 'channels.discord.token');
  const legacyPaidProvider = 'gr' + 'oq';
  deleteDeep(config, `models.providers.${legacyPaidProvider}`);
  deleteDeep(config, `plugins.entries.${legacyPaidProvider}`);
  deleteDeep(config, `auth.order.${legacyPaidProvider}`);
  if (config.auth?.profiles) {
    for (const key of Object.keys(config.auth.profiles)) {
      if (key.startsWith(`${legacyPaidProvider}:`)) delete config.auth.profiles[key];
    }
  }

  setDeep(config, 'agents.defaults.workspace', process.env.OPENCLAW_WORKSPACE || process.cwd());
  setDeep(config, 'agents.defaults.models', buildAllowedModels(policy, modelChain));
  setDeep(config, 'agents.defaults.model', buildModelDefaults(modelChain));
  if (profilesByProvider.google?.length) {
    setDeep(config, 'agents.defaults.memorySearch', {
      provider: 'gemini',
      enabled: true,
      model: process.env.CLAW_MEMORY_EMBEDDING_MODEL || 'gemini-embedding-001',
    });
  } else {
    setDeep(config, 'agents.defaults.memorySearch', { enabled: false });
  }
  setDeep(config, 'agents.defaults.heartbeat', {
    every: process.env.CLAW_HEARTBEAT_EVERY || '30m',
    model: modelChain[1]?.ref || modelChain[0]?.ref || 'google/gemini-2.5-flash-lite',
  });
  setDeep(config, 'agents.defaults.subagents', {
    model: modelChain[1]?.ref || modelChain[0]?.ref || 'google/gemini-2.5-flash-lite',
  });

  setDeep(config, 'gateway.mode', 'local');
  setDeep(config, 'gateway.port', Number(process.env.PORT || process.env.OPENCLAW_GATEWAY_PORT || 7860));
  setDeep(config, 'gateway.bind', process.env.OPENCLAW_GATEWAY_BIND || 'lan');

  setDeep(config, 'plugins.entries.telegram.enabled', true);
  deleteDeep(config, 'plugins.entries.discord');
  for (const [providerId, providerPolicy] of Object.entries(policy.providers)) {
    if (providerPolicy.plugin) {
      setDeep(config, `plugins.entries.${providerPolicy.plugin}.enabled`, Boolean(profilesByProvider[providerId]?.length));
    }
  }

  setDeep(config, 'models.providers.google.api', 'google-generative-ai');
  setDeep(config, 'models.providers.google.models', policy.providers.google.models.free.map(({ id, name }) => ({ id, name })));
  setDeep(config, 'models.providers.openrouter.models', [
    ...(policy.providers.openrouter.models.free || []),
    ...(paidEnabled ? (policy.providers.openrouter.models.paid || []) : []),
  ].map(({ id, name }) => ({ id, name })));

  const authProfiles = {};
  const authOrder = {};
  for (const [providerId, profiles] of Object.entries(profilesByProvider)) {
    if (!profiles.length) continue;
    const authProvider = policy.providers[providerId].authProvider || providerId;
    authOrder[authProvider] = profiles.map((profile) => profile.id);
    for (const profile of profiles) {
      authProfiles[profile.id] = { provider: authProvider, mode: 'api_key' };
    }
  }
  setDeep(config, 'auth.profiles', authProfiles);
  setDeep(config, 'auth.order', authOrder);
  setDeep(config, 'auth.cooldowns', {
    billingBackoffHours: 24,
    billingMaxHours: 168,
    failureWindowHours: 24,
    overloadedProfileRotations: 1,
    rateLimitedProfileRotations: 3,
  });

  setDeep(config, 'channels.telegram.enabled', true);
  setDeep(config, 'channels.telegram.groups', { '*': { requireMention: true } });
  setDeep(config, 'channels.discord.enabled', false);
  return config;
}

function buildAllowedModels(policy, modelChain) {
  const allowed = {};
  for (const model of modelChain) {
    allowed[model.ref] = { alias: model.alias || model.name || model.ref };
  }
  for (const providerPolicy of Object.values(policy.providers)) {
    for (const model of providerPolicy.models?.free || []) {
      allowed[model.ref] = allowed[model.ref] || { alias: model.alias || model.name || model.ref };
    }
  }
  return allowed;
}

function buildModelDefaults(modelChain) {
  if (!modelChain.length) {
    return {
      primary: 'google/gemini-2.5-flash-lite',
      fallbacks: ['google/gemini-2.5-flash'],
    };
  }
  const [primary, ...fallbacks] = modelChain;
  return {
    primary: primary.ref,
    fallbacks: fallbacks.map((model) => model.ref),
  };
}

function writeRuntimeAuth(profilesByProvider) {
  const profiles = { version: 1, profiles: {} };
  for (const providerProfiles of Object.values(profilesByProvider)) {
    for (const profile of providerProfiles) {
      profiles.profiles[profile.id] = {
        type: 'api_key',
        provider: profile.authProvider,
        key: profile.key,
      };
    }
  }
  const runtimePath = path.join(stateRoot, 'agents', 'main', 'agent', 'auth-profiles.json');
  fs.mkdirSync(path.dirname(runtimePath), { recursive: true });
  fs.writeFileSync(runtimePath, `${JSON.stringify(profiles, null, 2)}\n`);
}

function summarize(profilesByProvider, modelChain, paidEnabled) {
  const profileSummary = Object.fromEntries(
    Object.entries(profilesByProvider).map(([provider, profiles]) => [provider, profiles.map((profile) => `${profile.id}:${profile.tier}`)]),
  );
  return {
    configPath,
    authProfilePath: path.join(stateRoot, 'agents', 'main', 'agent', 'auth-profiles.json'),
    paidFallbackEnabled: paidEnabled,
    profiles: profileSummary,
    modelOrder: modelChain.map((model) => `${model.ref}:${model.tier}`),
  };
}

try {
  const policy = JSON.parse(fs.readFileSync(policyPath, 'utf8'));
  const fileEnv = parseEnvFile(envPath);
  const env = mergeEnv(fileEnv);
  const paidEnabled = truthy(env[policy.paidFallbackEnv] || env.CLAW_ENABLE_PAID_FALLBACK);
  const profilesByProvider = {};
  for (const [providerId, providerPolicy] of Object.entries(policy.providers)) {
    profilesByProvider[providerId] = providerPolicy.enabled
      ? collectProviderProfiles(providerId, providerPolicy, env, paidEnabled)
      : [];
  }
  const modelChain = buildModelChain(policy, profilesByProvider, paidEnabled);

  fs.mkdirSync(stateRoot, { recursive: true });
  writeEnvFile(envPath, env, collectKnownEnvKeys(policy));

  let baseConfig = {};
  if (fs.existsSync(configPath)) {
    baseConfig = JSON.parse(fs.readFileSync(configPath, 'utf8'));
  }
  const config = buildConfig(baseConfig, policy, env, profilesByProvider, modelChain, paidEnabled);
  fs.writeFileSync(configPath, `${JSON.stringify(config, null, 2)}\n`);
  writeRuntimeAuth(profilesByProvider);

  const summary = summarize(profilesByProvider, modelChain, paidEnabled);
  console.log(JSON.stringify(summary, null, 2));
  if (paidEnabled) {
    console.error('Paid fallback is ENABLED. Paid profiles/models are ordered after free profiles/models.');
  }
} catch (err) {
  console.error('Error:', err.message);
  process.exit(1);
}
